//! `cargo xtask typescript [--cli PATH] [--out DIR]`: the TypeScript client's generated bindings
//! (`typescript/src/generated/`, not committed; `typescript/README.md`).
//!
//! The only input is `solidcraft-cli commands --schemas` from the build, as for the Python client
//! (`python.rs`), so the bindings cannot drift from what the program does: every engine command
//! becomes an entry of `CommandParams`, its input schema as a TypeScript type, which
//! `Session.run("solid.box", {...})` checks in the editor. Planned commands are left out.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use serde_json::Value;

/// Named `$defs` the command contracts share, written once as type aliases.
const ALIASES: &[(&str, &str, &str)] = &[
    ("LengthExpr", "Length", "number | string"),
    ("AngleExpr", "Angle", "number | string"),
    ("Expr", "Expr", "number | string"),
    ("NumberExpr", "NumberExpr", "number | string"),
    ("PointExpr3", "Point3", "[Length, Length, Length] | { x: Length; y: Length; z: Length }"),
    ("PointExpr2", "Point2", "[Length, Length] | { x: Length; y: Length }"),
    ("Vec3", "Vec3", "[number, number, number]"),
    ("Vec2", "Vec2", "[number, number]"),
    ("StringList", "Names", "string | string[]"),
];

pub fn run(root: &Path, args: &[&str]) -> Result<(), String> {
    let mut cli: Option<PathBuf> = None;
    let mut out = root.join("typescript/src/generated");
    let mut i = 0;
    while let Some(a) = args.get(i) {
        match *a {
            "--cli" => cli = Some(PathBuf::from(args.get(i + 1).ok_or("typescript: --cli needs a path")?)),
            "--out" => out = PathBuf::from(args.get(i + 1).ok_or("typescript: --out needs a folder")?),
            other => return Err(format!("typescript: unknown argument `{other}` (it takes --cli PATH, --out DIR)")),
        }
        i += 2;
    }
    let cli = match cli {
        Some(c) => c,
        None => crate::python::build_cli(root)?,
    };
    let commands = crate::python::cli_json(&cli, &["commands", "--schemas"])?;
    let commands = commands.as_array().ok_or("typescript: `commands --schemas` is not a list")?;
    let version = cli_version(&cli)?;
    let text = generate(commands, &version)?;
    std::fs::create_dir_all(&out).map_err(|e| format!("typescript: {}: {e}", out.display()))?;
    std::fs::write(out.join("commands.ts"), text).map_err(|e| format!("typescript: commands.ts: {e}"))?;
    let runnable = commands.iter().filter(|c| !crate::python::is_planned(c)).count();
    println!("typescript: {runnable} commands, version {version} → {}", out.display());
    Ok(())
}

/// `0.52.0` from `solidcraft-cli --version` (`solidcraft-cli 0.52.0`).
fn cli_version(cli: &Path) -> Result<String, String> {
    let out = Command::new(cli).arg("--version").output().map_err(|e| format!("typescript: {}: {e}", cli.display()))?;
    let text = String::from_utf8_lossy(&out.stdout);
    text.split_whitespace()
        .last()
        .map(str::to_string)
        .filter(|v| v.chars().next().is_some_and(|c| c.is_ascii_digit()))
        .ok_or_else(|| format!("typescript: no version in `{}`", text.trim()))
}

/// The text of `commands.ts`.
pub fn generate(commands: &[Value], version: &str) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("// Generated by `cargo xtask typescript` from `solidcraft-cli commands --schemas`. Do not edit.\n\n");
    let _ = writeln!(out, "export const VERSION = {};\n", lit(version));
    for (_, alias, ty) in ALIASES {
        let _ = writeln!(out, "export type {alias} = {ty};");
    }
    out.push('\n');
    let mut seen = BTreeSet::new();
    let mut entries = String::new();
    for c in commands {
        if crate::python::is_planned(c) {
            continue;
        }
        let id = c["id"].as_str().ok_or("typescript: a command has no id")?;
        if !seen.insert(id.to_string()) {
            return Err(format!("typescript: command `{id}` is listed twice"));
        }
        let input = &c["input"];
        let defs = &input["$defs"];
        let ty = if input.is_object() { object(input, defs, 1) } else { "Record<string, unknown>".into() };
        let summary = c["label"].as_str().unwrap_or_default();
        let prose = input["description"].as_str().unwrap_or_default();
        let _ = writeln!(entries, "{}  {}: {ty};", jsdoc(&format!("{summary}. {prose}"), "  "), lit(id));
    }
    out.push_str("/** Every engine command's parameters, by command id. */\nexport interface CommandParams {\n");
    out.push_str(&entries);
    out.push_str("}\n\nexport type CommandId = keyof CommandParams;\n");
    Ok(out)
}

fn lit(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_else(|_| "\"\"".into())
}

fn jsdoc(text: &str, pad: &str) -> String {
    let clean = text.trim().trim_start_matches(". ").replace("*/", "* /");
    if clean.is_empty() {
        return String::new();
    }
    let lines: Vec<&str> = clean.lines().map(str::trim_end).collect();
    if lines.len() == 1 {
        return format!("{pad}/** {} */\n", lines[0]);
    }
    let mut out = format!("{pad}/**\n");
    for l in lines {
        let _ = writeln!(out, "{pad} * {l}");
    }
    let _ = writeln!(out, "{pad} */");
    out
}

/// A property name as TypeScript writes it: bare when it is an identifier, else quoted.
fn key(name: &str) -> String {
    let ident = name.chars().next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if ident { name.to_string() } else { lit(name) }
}

/// The object type of a schema with `properties` (the root of a command's input, or a nested one).
fn object(s: &Value, defs: &Value, depth: u32) -> String {
    let Some(props) = s["properties"].as_object() else {
        return "Record<string, unknown>".into();
    };
    let required: BTreeSet<&str> = s["required"].as_array().map(|r| r.iter().filter_map(Value::as_str).collect()).unwrap_or_default();
    let pad = "  ".repeat(depth as usize + 1);
    let mut out = String::from("{\n");
    for (name, p) in props {
        let opt = if required.contains(name.as_str()) { "" } else { "?" };
        out.push_str(&jsdoc(p["description"].as_str().unwrap_or_default(), &pad));
        let _ = writeln!(out, "{pad}{}{opt}: {};", key(name), annotation(p, defs, depth + 1));
    }
    if s["additionalProperties"] != Value::Bool(false) {
        let _ = writeln!(out, "{pad}[key: string]: unknown;");
    }
    out.push_str(&"  ".repeat(depth as usize));
    out.push('}');
    out
}

/// The TypeScript type of a JSON Schema, read against `defs`. Deliberately shallow past a few
/// levels (`unknown`): the engine checks parameters; the types are for people and editors.
fn annotation(s: &Value, defs: &Value, depth: u32) -> String {
    if depth > 6 {
        return "unknown".into();
    }
    if let Some(r) = s["$ref"].as_str() {
        let name = r.rsplit('/').next().unwrap_or_default();
        if let Some((_, alias, _)) = ALIASES.iter().find(|(def, _, _)| *def == name) {
            return (*alias).into();
        }
        return annotation(&defs[name], defs, depth + 1);
    }
    if let Some(c) = s.get("const") {
        return serde_json::to_string(c).unwrap_or_else(|_| "unknown".into());
    }
    if let Some(e) = s["enum"].as_array() {
        let vals: Vec<String> = e.iter().filter(|v| !v.is_null()).filter_map(|v| serde_json::to_string(v).ok()).collect();
        return if vals.is_empty() { "null".into() } else { vals.join(" | ") };
    }
    for k in ["anyOf", "oneOf"] {
        if let Some(alts) = s[k].as_array() {
            if s["properties"].is_object() {
                // properties beside an anyOf of required sets: the properties carry the types
                return object(s, defs, depth);
            }
            return union(alts.iter().map(|a| annotation(a, defs, depth + 1)));
        }
    }
    match &s["type"] {
        Value::String(t) => typed(t, s, defs, depth),
        Value::Array(ts) => union(ts.iter().filter_map(Value::as_str).map(|t| typed(t, s, defs, depth))),
        _ if s["properties"].is_object() => object(s, defs, depth),
        _ => "unknown".into(),
    }
}

fn typed(t: &str, s: &Value, defs: &Value, depth: u32) -> String {
    match t {
        "string" => "string".into(),
        "number" | "integer" => "number".into(),
        "boolean" => "boolean".into(),
        "null" => "null".into(),
        "object" => object(s, defs, depth),
        "array" => match s.get("items") {
            Some(items) if items.is_object() => {
                let inner = annotation(items, defs, depth + 1);
                let (min, max) = (s["minItems"].as_u64(), s["maxItems"].as_u64());
                match (min, max) {
                    (Some(a), Some(b)) if a == b && (2..=4).contains(&a) => format!("[{}]", vec![inner; a as usize].join(", ")),
                    _ if inner.contains(' ') => format!("({inner})[]"),
                    _ => format!("{inner}[]"),
                }
            }
            _ => "unknown[]".into(),
        },
        _ => "unknown".into(),
    }
}

/// `A | B` without repeats; `null` is kept out (an absent optional parameter is the same).
fn union(parts: impl Iterator<Item = String>) -> String {
    let mut seen: Vec<String> = Vec::new();
    for p in parts {
        if p != "null" && !seen.contains(&p) {
            seen.push(p);
        }
    }
    if seen.iter().any(|s| s == "unknown") {
        return "unknown".into();
    }
    if seen.is_empty() { "null".into() } else { seen.join(" | ") }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn schemas_become_typescript_types() {
        let defs = json!({"LengthExpr": {}, "Op": {"enum": ["new", "cut"]}});
        assert_eq!(annotation(&json!({"$ref": "#/$defs/LengthExpr"}), &defs, 0), "Length");
        assert_eq!(annotation(&json!({"$ref": "#/$defs/Op"}), &defs, 0), "\"new\" | \"cut\"");
        assert_eq!(annotation(&json!({"type": ["string", "null"]}), &defs, 0), "string");
        assert_eq!(
            annotation(&json!({"type": "array", "items": {"type": "number"}, "minItems": 3, "maxItems": 3}), &defs, 0),
            "[number, number, number]"
        );
        assert_eq!(
            annotation(&json!({"type": "array", "items": {"anyOf": [{"type": "number"}, {"type": "string"}]}}), &defs, 0),
            "(number | string)[]"
        );
    }

    #[test]
    fn commands_become_entries_and_planned_ones_are_left_out() {
        let cmds = vec![
            json!({"id": "solid.box", "label": "Box", "input": {"type": "object", "additionalProperties": false, "properties": {"length": {"$ref": "#/$defs/LengthExpr"}, "body-name": {"type": "string"}}, "required": ["length"], "$defs": {"LengthExpr": {}}}}),
            json!({"id": "solid.future", "label": "Planned", "input": null, "planned": "#1"}),
        ];
        let text = generate(&cmds, "1.2.3").unwrap();
        assert!(text.contains("export const VERSION = \"1.2.3\";"), "{text}");
        assert!(text.contains("\"solid.box\": {"), "{text}");
        assert!(text.contains("length: Length;"), "{text}");
        assert!(text.contains("\"body-name\"?: string;"), "{text}");
        assert!(!text.contains("[key: string]: unknown;\n  }"), "a closed schema takes no other keys: {text}");
        assert!(!text.contains("solid.future"), "planned commands are left out");
    }

    #[test]
    fn a_command_listed_twice_stops_the_generator() {
        let c = json!({"id": "a.b", "label": "", "input": null});
        assert!(generate(&[c.clone(), c], "0").is_err());
    }
}

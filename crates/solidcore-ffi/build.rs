//! Build script for `solidcore-ffi`.
//!
//! Always: generates `$OUT_DIR/units.rs`, which declares one module per file in
//! `src/units/*.rs` (so adding a unit wrapper never touches a shared file).
//!
//! With feature `cpp`:
//! 1. reads compiler settings from `bin/cpp/ffi.env` (preferred) or
//!    `bin/cpp/compile_commands.json` (fallback),
//! 2. compiles every `harness/cpp/shim/*.cpp` with the `cc` crate,
//! 3. links every static (`lib*.a`) or shared (`lib*.so`) library found in
//!    `bin/cpp/lib` (order: `LIBS`, else `SM_API` before `SMLib`, then the rest
//!    by name), plus system libraries (`SYSLIBS`, default none) and the C++
//!    runtime. Static libs are linked `-bundle` (not copied into the rlib; they
//!    are huge) so the final link of `difftest` pulls them from `bin/cpp/lib`.
//!
//! `SOLIDCORE_CPP_DIR` overrides the `bin/cpp` location. `scripts/fetch-cpp.sh`
//! downloads a prebuilt `bin/cpp` (or builds it with `harness/cpp/build.sh`).
//!
//! Shim compile caching: the `cc` crate (1.8) runs the C++ compiler through
//! `RUSTC_WRAPPER` when that is `sccache` (or cachepot/buildcache/kache), so
//! `RUSTC_WRAPPER=sccache` caches the shim objects as well as the Rust crates. To
//! cache only the C++, set `CXX="sccache c++"` instead; `cc` recognises the wrapper.
//! Nothing here needs to change for either.
//!
//! `ffi.env` format (one `KEY=VALUE` per line, `#` comments, values are
//! whitespace separated lists; relative paths are relative to the repo root):
//!
//! ```text
//! INCLUDE_DIRS=upstream/source/SMLib/inc upstream/source/SM_API/inc
//! DEFINES=NDEBUG SOME_FLAG=1
//! CXXFLAGS=-std=c++17
//! LIBS=SM_API SMLib          # optional explicit link order (names without lib/.a)
//! SYSLIBS=tbb tbbmalloc pthread
//! LIB_DIRS=/extra/lib/dir
//! ```

#![allow(
    clippy::expect_used,
    clippy::panic,
    clippy::unwrap_used,
    clippy::indexing_slicing,
    clippy::pedantic
)]
// Build scripts should fail loudly; the lint denies target library code.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let root = manifest
        .parent()
        .and_then(Path::parent)
        .expect("repo root")
        .to_path_buf();
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let cpp = env::var_os("CARGO_FEATURE_CPP").is_some();

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=SOLIDCORE_CPP_DIR");

    // ---- unit module registry -------------------------------------------
    let units_dir = manifest.join("src").join("units");
    println!("cargo:rerun-if-changed={}", units_dir.display());
    let mut reg = String::from("// @generated by solidcore-ffi/build.rs\n");
    if cpp {
        for file in sorted_files(&units_dir, "rs") {
            let stem = file
                .file_stem()
                .and_then(|s| s.to_str())
                .expect("utf-8 file name")
                .to_string();
            reg.push_str(&format!(
                "#[path = {:?}]\npub mod {stem};\n",
                file.display().to_string()
            ));
        }
    }
    fs::write(out_dir.join("units.rs"), reg).expect("write units.rs");

    if !cpp {
        return;
    }

    // ---- locate C++ build --------------------------------------------------
    let cpp_dir = env::var_os("SOLIDCORE_CPP_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| root.join("bin").join("cpp"));
    let lib_dir = cpp_dir.join("lib");
    let env_file = cpp_dir.join("ffi.env");
    let cc_json = cpp_dir.join("compile_commands.json");
    println!("cargo:rerun-if-changed={}", env_file.display());
    println!("cargo:rerun-if-changed={}", cc_json.display());
    println!("cargo:rerun-if-changed={}", lib_dir.display());

    let cfg = if env_file.is_file() {
        parse_env_file(&env_file, &root)
    } else if cc_json.is_file() {
        parse_compile_commands(&cc_json)
    } else {
        Config::default()
    };

    // ---- compile shims -------------------------------------------------------
    let shim_dir = root.join("harness").join("cpp").join("shim");
    println!("cargo:rerun-if-changed={}", shim_dir.display());
    let shims = sorted_files(&shim_dir, "cpp");
    for f in &shims {
        println!("cargo:rerun-if-changed={}", f.display());
    }
    // headers and the `.inc` files a shim includes (not compiled on their own)
    for h in sorted_files(&shim_dir, "h")
        .into_iter()
        .chain(sorted_files(&shim_dir, "inc"))
    {
        println!("cargo:rerun-if-changed={}", h.display());
    }
    if !shims.is_empty() {
        let mut b = cc::Build::new();
        b.cpp(true).warnings(false).include(&shim_dir);
        // Default include dirs, then configured ones.
        for d in ["upstream/source/SMLib/inc", "upstream/source/SM_API/inc"] {
            let p = root.join(d);
            if p.is_dir() {
                b.include(p);
            }
        }
        for d in &cfg.include_dirs {
            b.include(d);
        }
        for d in &cfg.defines {
            match d.split_once('=') {
                Some((k, v)) => b.define(k, Some(v)),
                None => b.define(d, None),
            };
        }
        let has_std = cfg.cxxflags.iter().any(|f| f.starts_with("-std="));
        if !has_std {
            b.flag("-std=c++17");
        }
        for f in &cfg.cxxflags {
            b.flag(f);
        }
        b.files(&shims);
        b.compile("solidcore_shims");
    }

    // ---- link upstream libs ------------------------------------------------------
    if !lib_dir.is_dir() {
        panic!(
            "solidcore-ffi: feature `cpp` needs the C++ kernel built into {} \
             (run harness/cpp/build.sh)",
            lib_dir.display()
        );
    }
    println!("cargo:rustc-link-search=native={}", lib_dir.display());
    println!("cargo:lib_dir={}", lib_dir.display());
    for d in &cfg.lib_dirs {
        println!("cargo:rustc-link-search=native={}", d.display());
    }
    let order = if cfg.libs.is_empty() {
        vec!["SM_API".to_string(), "SMLib".to_string()]
    } else {
        cfg.libs.clone()
    };
    let libs = discover_libs(&lib_dir, &order);
    if libs.is_empty() {
        panic!(
            "solidcore-ffi: no lib*.a / lib*.so found in {}",
            lib_dir.display()
        );
    }
    for (name, kind) in &libs {
        if *kind == "static" {
            println!("cargo:rustc-link-lib=static:-bundle={name}");
        } else {
            println!("cargo:rustc-link-lib=dylib={name}");
        }
    }
    // A's CMake build (harness/cpp/CMakeLists.txt) does not use TBB.
    for l in cfg.syslibs.as_deref().unwrap_or(&[]) {
        println!("cargo:rustc-link-lib=dylib={l}");
    }
    // Apple, FreeBSD and OpenBSD (clang platforms) ship libc++, not libstdc++. NetBSD
    // still defaults to GCC and libstdc++.
    let os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let cxx = if matches!(os.as_str(), "macos" | "ios" | "freebsd" | "openbsd") {
        "c++"
    } else {
        "stdc++"
    };
    println!("cargo:rustc-link-lib=dylib={cxx}");
    println!("cargo:rustc-link-lib=dylib=m");
}

#[derive(Default)]
struct Config {
    include_dirs: Vec<PathBuf>,
    defines: Vec<String>,
    cxxflags: Vec<String>,
    libs: Vec<String>,
    syslibs: Option<Vec<String>>,
    lib_dirs: Vec<PathBuf>,
}

fn sorted_files(dir: &Path, ext: &str) -> Vec<PathBuf> {
    let mut v: Vec<PathBuf> = fs::read_dir(dir)
        .map(|rd| {
            rd.filter_map(|e| e.ok().map(|e| e.path()))
                .filter(|p| p.is_file() && p.extension().and_then(|e| e.to_str()) == Some(ext))
                .collect()
        })
        .unwrap_or_default();
    v.sort();
    v
}

fn abs(root: &Path, p: &str) -> PathBuf {
    let pb = PathBuf::from(p);
    if pb.is_absolute() {
        pb
    } else {
        root.join(pb)
    }
}

fn parse_env_file(path: &Path, root: &Path) -> Config {
    let text = fs::read_to_string(path).expect("read ffi.env");
    let mut kv: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for line in text.lines() {
        let line = line.split('#').next().unwrap_or("").trim();
        if let Some((k, v)) = line.split_once('=') {
            kv.entry(k.trim().to_string())
                .or_default()
                .extend(v.split_whitespace().map(str::to_string));
        }
    }
    let get = |k: &str| kv.get(k).cloned().unwrap_or_default();
    Config {
        include_dirs: get("INCLUDE_DIRS").iter().map(|p| abs(root, p)).collect(),
        defines: get("DEFINES"),
        cxxflags: get("CXXFLAGS"),
        libs: get("LIBS"),
        syslibs: kv.get("SYSLIBS").cloned(),
        lib_dirs: get("LIB_DIRS").iter().map(|p| abs(root, p)).collect(),
    }
}

/// Fallback: harvest -I/-isystem/-D/-std from SMLib / SM_API entries.
fn parse_compile_commands(path: &Path) -> Config {
    let text = fs::read_to_string(path).expect("read compile_commands.json");
    let json: serde_json::Value = serde_json::from_str(&text).expect("parse compile_commands.json");
    let mut cfg = Config::default();
    let entries = json.as_array().cloned().unwrap_or_default();
    for e in entries {
        let file = e.get("file").and_then(|f| f.as_str()).unwrap_or("");
        if !(file.contains("/source/SMLib/") || file.contains("/source/SM_API/")) {
            continue;
        }
        let dir = PathBuf::from(e.get("directory").and_then(|d| d.as_str()).unwrap_or("."));
        let args: Vec<String> = match e.get("arguments").and_then(|a| a.as_array()) {
            Some(a) => a
                .iter()
                .filter_map(|s| s.as_str().map(str::to_string))
                .collect(),
            None => e
                .get("command")
                .and_then(|c| c.as_str())
                .unwrap_or("")
                .split_whitespace()
                .map(str::to_string)
                .collect(),
        };
        let mut it = args.iter().peekable();
        while let Some(a) = it.next() {
            let (inc, val) = if a == "-I" || a == "-isystem" {
                (true, it.next().cloned())
            } else if let Some(v) = a.strip_prefix("-isystem") {
                (true, Some(v.to_string()))
            } else if let Some(v) = a.strip_prefix("-I") {
                (true, Some(v.to_string()))
            } else {
                (false, None)
            };
            if inc {
                if let Some(v) = val {
                    let p = abs(&dir, &v);
                    if !cfg.include_dirs.contains(&p) {
                        cfg.include_dirs.push(p);
                    }
                }
                continue;
            }
            if a == "-D" {
                if let Some(v) = it.next() {
                    if !cfg.defines.contains(v) {
                        cfg.defines.push(v.clone());
                    }
                }
            } else if let Some(v) = a.strip_prefix("-D") {
                if !cfg.defines.iter().any(|d| d == v) {
                    cfg.defines.push(v.to_string());
                }
            } else if (a.starts_with("-std=") || is_codegen_fflag(a)) && !cfg.cxxflags.contains(a) {
                cfg.cxxflags.push(a.clone());
            }
        }
    }
    cfg
}

/// `-f...` flags that affect numerics/ABI and should match the kernel build.
fn is_codegen_fflag(a: &str) -> bool {
    a.starts_with("-f") && !a.starts_with("-fdiagnostics") && !a.starts_with("-fcolor")
}

/// Returns (name, kind) in link order: explicit `LIBS` order first, then the
/// remaining libraries sorted by name. Static libs win over shared ones.
fn discover_libs(lib_dir: &Path, explicit: &[String]) -> Vec<(String, &'static str)> {
    let mut found: BTreeMap<String, &'static str> = BTreeMap::new();
    let mut entries: Vec<PathBuf> = fs::read_dir(lib_dir)
        .map(|rd| rd.filter_map(|e| e.ok().map(|e| e.path())).collect())
        .unwrap_or_default();
    entries.sort();
    for p in entries {
        let Some(fname) = p.file_name().and_then(|f| f.to_str()) else {
            continue;
        };
        let Some(rest) = fname.strip_prefix("lib") else {
            continue;
        };
        if let Some(name) = rest.strip_suffix(".a") {
            found.insert(name.to_string(), "static");
        } else if let Some(name) = rest.strip_suffix(".so") {
            found.entry(name.to_string()).or_insert("dylib");
        }
    }
    let mut out = Vec::new();
    for n in explicit {
        if let Some(k) = found.remove(n) {
            out.push((n.clone(), k));
        }
    }
    out.extend(found);
    out
}

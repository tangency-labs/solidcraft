/// The keys of a member's tooth count and shift inputs.
fn member_keys(member: u8) -> (&'static str, &'static str) {
    match member {
        2 => ("teeth2", "shift2"),
        3 => ("teeth3", "shift3"),
        _ => ("teeth", "shift"),
    }
}

/// Inputs and the transverse quantities every involute member shares.
struct Common {
    p: String,
    mt: String,
    at: String,
    teeth: &'static str,
    shift: &'static str,
    bl: String,
    helix: Option<String>,
}

fn common(v: &mut Vars, src: &TeethSource, g: &Involute) -> Result<Common, String> {
    let p = format!("g{}_", src.member);
    v.input("module", g.module, Quantity::Length, "normal module");
    v.input("pressure_angle", g.pressure_angle, Quantity::Angle, "normal pressure angle");
    let helix = if g.helix != 0.0 {
        v.input("helix", g.helix.abs(), Quantity::Angle, "helix angle at the pitch circle");
        Some("helix".to_string())
    } else {
        None
    };
    let (teeth, shift) = member_keys(src.member);
    v.input(teeth, f64::from(g.teeth), Quantity::Number, &format!("{}: number of teeth", src.who));
    v.input(shift, g.shift, Quantity::Number, &format!("{}: profile shift coefficient", src.who));
    v.input("backlash", src.backlash, Quantity::Length, "backlash at the pitch circle");
    v.input(&src.face_key, src.face, Quantity::Length, "face width");
    let (mt, at) = if helix.is_some() {
        v.derived(&format!("{p}mt"), "{module} / cos({helix})".into(), Quantity::Length, "transverse module")?;
        v.derived(&format!("{p}at"), "atan(tan({pressure_angle}) / cos({helix}))".into(), Quantity::Angle, "transverse pressure angle")?;
        (format!("{{{p}mt}}"), format!("{{{p}at}}"))
    } else {
        ("{module}".to_string(), "{pressure_angle}".to_string())
    };
    let extra = g.backlash - src.backlash;
    let bl = if extra.abs() > 1e-12 { format!("({{backlash}} + {})", literal(extra, Quantity::Length)) } else { "{backlash}".to_string() };
    v.derived(&format!("{p}r"), format!("{mt} * {{{teeth}}} / 2"), Quantity::Length, "pitch radius")?;
    v.derived(&format!("{p}rb"), format!("{{{p}r}} * cos({at})"), Quantity::Length, "base radius")?;
    Ok(Common { p, mt, at, teeth, shift, bl, helix })
}

/// `phase` and a side's angle: `PH + (A)` or `PH - (A)`.
fn side_angle(phase: &str, sign: f64, a: &str) -> String {
    match (phase.is_empty(), sign > 0.0) {
        (true, true) => format!("({a})"),
        (true, false) => format!("-({a})"),
        (false, true) => format!("{phase} + ({a})"),
        (false, false) => format!("{phase} - ({a})"),
    }
}

/// A curve of radius `r(t)` and angle `phase ± a(t)`.
fn polar_curve(name: &str, r: &str, a: &str, phase: &str, sign: f64, start: String, end: String, tolerance: f64) -> Curve {
    let ang = side_angle(phase, sign, a);
    Curve { name: name.into(), x: format!("{r} * cos({ang})"), y: format!("{r} * sin({ang})"), start, end, tolerance }
}

/// A point at radius `r` (template) and angle `phase ± a` (template, an angle).
fn polar_point(r: &str, a: &str, phase: &str, sign: f64) -> [String; 2] {
    let ang = side_angle(phase, sign, a);
    [format!("{r} * cos({ang})"), format!("{r} * sin({ang})")]
}

fn tolerances(m: f64) -> (f64, f64) {
    let clamp = |t: f64| t.clamp(1e-4, 10.0);
    (clamp(PROFILE_TOLERANCE * m), clamp(FILLET_TOLERANCE * m))
}

/// Radius and polar angle of the involute (upper side, phase 0) at roll `u`.
fn involute_at(v: &Vars, p: &str, hb_key: &str, u: f64) -> Option<V2> {
    let rb = v.value(&format!("{p}rb"))?;
    let hb = v.value(hb_key)?;
    Some(V2::polar(rb * (1.0 + u * u).sqrt(), hb - u + u.atan()))
}

/// The fillet's point (upper side, phase 0) at `t` (modules along the cutter).
fn fillet_at(v: &Vars, p: &str, t: f64) -> Option<V2> {
    let m = v.value("module")?;
    let (rho, bc, r, th0) = (v.value(&format!("{p}rho"))?, v.value(&format!("{p}bc"))?, v.value(&format!("{p}r"))?, v.value(&format!("{p}th0"))?);
    let k = 1.0 + rho / (t * m).hypot(bc);
    let (x, y) = (t * m * k, r + bc * k);
    Some(V2::polar(x.hypot(y), th0 + t * m / r - (x / y).atan()))
}

/// Tooth 0's angle in the formulas: one of the source's phase templates whose value is
/// `phase` to a whole tooth (as a variable of its own, corrected by those whole teeth), else
/// `phase` as a number; empty for 0.
fn phase_text(v: &mut Vars, src: &TeethSource, phase: f64, teeth: u32) -> Result<String, String> {
    let period = 2.0 * PI / f64::from(teeth.max(1));
    for (key, tpl) in &src.phases {
        let look = |k: &str| v.value(k).or_else(|| src.extra.value(k));
        let Ok(value) = eval(tpl, &look) else { continue };
        let d = value - phase;
        let k = (d / period).round();
        if !((d - k * period).abs() <= 1e-9 * phase.abs().max(1.0)) {
            continue;
        }
        for name in keys(tpl) {
            if v.get(&name).is_none()
                && let Some(var) = src.extra.get(&name)
            {
                v.list.push(var.clone());
            }
        }
        let (teeth_key, _) = member_keys(src.member);
        let tpl = if k == 0.0 { tpl.clone() } else { format!("{tpl} - {} * 2 * pi / {{{teeth_key}}} * 1 rad", number(k)) };
        v.derived(key, tpl, Quantity::Angle, &format!("{}: tooth 0's angle", src.who))?;
        return Ok(format!("{{{key}}}"));
    }
    Ok(if phase.abs() > 0.0 { literal(phase, Quantity::Angle) } else { String::new() })
}


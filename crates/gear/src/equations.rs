/// Where a set's members sit, as formulas: the centres (in the set's frame) of a pair's gear 2
/// and a planetary set's planets, over the variables `vars` (inputs shared with the teeth's
/// formulas, and the working centre distance worked out from them), so a parametric set's
/// mates follow its module, tooth counts and shifts.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Placing {
    pub vars: Vars,
    /// (index into the plan's bodies, x, y): the body's centre in the set's frame (templates).
    pub centres: Vec<(usize, String, String)>,
}

impl Placing {
    /// A centre's value: (x, y) in mm.
    pub fn value(&self, x: &str, y: &str) -> Result<(f64, f64), String> {
        Ok((self.vars.eval(x, None)?, self.vars.eval(y, None)?))
    }
}

/// The working centre distance of two external gears as formulas: `{mesh_cd}` in `v`, from the
/// inputs (module, pressure angle, helix, both tooth counts and shifts; gear 2's under
/// `keys2`). The working pressure angle solves inv(a) = 2 tan(an) (x1 + x2) / (z1 + z2) +
/// inv(at) by five Newton steps from (3 inv)^(1/3), which lies above it (tan a - a > a^3 / 3),
/// so the steps come down to it without overshooting. Returns its value.
pub fn mesh_vars(v: &mut Vars, g1: &Involute, g2: &Involute, keys2: (&str, &str)) -> Result<f64, String> {
    v.input("module", g1.module, Quantity::Length, "normal module");
    v.input("pressure_angle", g1.pressure_angle, Quantity::Angle, "normal pressure angle");
    let helix = g1.helix != 0.0;
    if helix {
        v.input("helix", g1.helix.abs(), Quantity::Angle, "helix angle at the pitch circle");
    }
    v.input("teeth", f64::from(g1.teeth), Quantity::Number, "gear 1: number of teeth");
    v.input("shift", g1.shift, Quantity::Number, "gear 1: profile shift coefficient");
    v.input(keys2.0, f64::from(g2.teeth), Quantity::Number, "gear 2: number of teeth");
    v.input(keys2.1, g2.shift, Quantity::Number, "gear 2: profile shift coefficient");
    let (mt, at) = if helix {
        v.derived("mesh_mt", "{module} / cos({helix})".into(), Quantity::Length, "transverse module")?;
        v.derived("mesh_at", "atan(tan({pressure_angle}) / cos({helix}))".into(), Quantity::Angle, "transverse pressure angle")?;
        ("{mesh_mt}", "{mesh_at}")
    } else {
        ("{module}", "{pressure_angle}")
    };
    let (z2, x2) = keys2;
    v.derived(
        "mesh_inv",
        format!("2 * tan({{pressure_angle}}) * ({{shift}} + {{{x2}}}) / ({{teeth}} + {{{z2}}}) + tan({at}) - {at} / (1 rad)"),
        Quantity::Number,
        "involute of the working pressure angle",
    )?;
    v.derived("mesh_aw0", "(3 * max({mesh_inv}, 0.0000001)) ^ (1 / 3) * 1 rad".into(), Quantity::Angle, "working pressure angle, first guess")?;
    for i in 1..=5 {
        let w = format!("{{mesh_aw{}}}", i - 1);
        v.derived(
            &format!("mesh_aw{i}"),
            format!("{w} - (tan({w}) - {w} / (1 rad) - {{mesh_inv}}) / tan({w}) ^ 2 * 1 rad"),
            Quantity::Angle,
            "working pressure angle, a Newton step on",
        )?;
    }
    v.derived("mesh_cd", format!("{mt} * ({{teeth}} + {{{z2}}}) / 2 * cos({at}) / cos({{mesh_aw5}})"), Quantity::Length, "working centre distance")
}

/// The cell of an external gear, tooth 0 at `phase`.
fn external(src: &TeethSource, g: &Involute, f: &ToothFlank, phase: f64) -> Result<ToothCell, String> {
    if f.pointed || f.fillet.len() < 2 || f.flank.len() < 2 || f.defect().is_some() {
        return Err("the tooth has no fillet, flank or tip land of its own".into());
    }
    let mut v = Vars::default();
    let c = common(&mut v, src, g)?;
    let (p, mt, at, teeth, shift, bl) = (&c.p, &c.mt, &c.at, c.teeth, c.shift, &c.bl);
    let m = g.module;
    let ha = number(g.rack.addendum);
    let hf = number(g.rack.dedendum);
    let ts = if g.tip_shortening.abs() > 1e-12 { format!(" - {}", literal(g.tip_shortening, Quantity::Length)) } else { String::new() };
    let mut exact = true;
    let ra = v.derived(&format!("{p}ra"), format!("{{{p}r}} + ({ha} + {{{shift}}}) * {{module}}{ts}"), Quantity::Length, "tip radius")?;
    if (ra - f.ra).abs() > 1e-9 * ra.max(1.0) {
        // (A tip lowered to keep a land: no closed formula.)
        return Err("the tip is lowered to keep a land".into());
    }
    v.derived(&format!("{p}rf"), format!("{{{p}r}} - ({hf} - {{{shift}}}) * {{module}}"), Quantity::Length, "root radius")?;
    v.derived(
        &format!("{p}hb"),
        format!("(pi * {mt} / 2 + 2 * {{{shift}}} * {{module}} * tan({at}) - {bl}) / (2 * {{{p}r}}) * 1 rad + tan({at}) * 1 rad - {at}"),
        Quantity::Angle,
        "half the tooth's angle at the base circle",
    )?;
    v.derived(
        &format!("{p}rho"),
        format!(
            "min({} * {{module}}, 0.999 * max(pi * {mt} / 4 - {hf} * {{module}} * tan({at}), 0 mm) / (1 / cos({at}) - tan({at})))",
            number(g.rack.root_radius)
        ),
        Quantity::Length,
        "the cutter's tip fillet radius",
    )?;
    v.derived(&format!("{p}vc"), format!("{{{p}rho}} - {hf} * {{module}}"), Quantity::Length, "the cutter's fillet centre below its datum line")?;
    v.derived(
        &format!("{p}uc"),
        format!("pi * {mt} / 4 + {{{p}vc}} * tan({at}) - {{{p}rho}} / cos({at})"),
        Quantity::Length,
        "the cutter's fillet centre from the space's middle",
    )?;
    v.derived(&format!("{p}bc"), format!("{{{shift}}} * {{module}} + {{{p}vc}}"), Quantity::Length, "the fillet centre below the pitch line")?;
    v.derived(
        &format!("{p}th0"),
        format!("pi / {{{teeth}}} * 1 rad - ({{{p}uc}} + {bl} / 2) / {{{p}r}} * 1 rad"),
        Quantity::Angle,
        "half the tooth's angle at the root",
    )?;
    let tf = v.derived(
        &format!("{p}tf"),
        format!("-{{{p}bc}} / tan({at}) / {{module}}"),
        Quantity::Number,
        "where the fillet ends (modules along the cutter)",
    )?;
    let u0 = v.derived(
        &format!("{p}u0"),
        format!("tan({at}) + ({{{p}bc}} - {{{p}rho}} * sin({at})) / ({{{p}rb}} * sin({at}))"),
        Quantity::Number,
        "the involute's roll where it starts",
    )?;
    let u1 = v.derived(&format!("{p}u1"), format!("sqrt(({{{p}ra}} / {{{p}rb}}) ^ 2 - 1)"), Quantity::Number, "the involute's roll at the tip")?;
    let rb = v.value(&format!("{p}rb")).unwrap_or(0.0);
    // Where the crate's flank starts: the formula's form circle, or (undercut) where the
    // trochoid crosses the involute.
    let handover = f.flank[0].0;
    let r_form = rb * (1.0 + u0 * u0).sqrt();
    let (fillet_range, flank_start) = if u0 >= 0.0 && (r_form - handover).abs() <= 1e-7 * m.max(1.0) {
        ((String::from("0"), format!("{{{p}tf}}")), format!("{{{p}u0}}"))
    } else {
        exact = false;
        let (tc, uc) = crossing(&v, p, handover, tf).ok_or("the fillet and the involute don't cross")?;
        ((String::from("0"), number(tc)), number(uc))
    };
    let _ = u1;
    let (tol_flank, tol_fillet) = tolerances(m);
    let ph = phase_text(&mut v, src, phase, g.teeth)?;
    let r_inv = format!("{{{p}rb}} * sqrt(1 + t ^ 2)");
    let a_inv = format!("{{{p}hb}} - t * 1 rad + atan(t)");
    let k = format!("(1 + {{{p}rho}} / hypot(t * {{module}}, {{{p}bc}}))");
    let fx = format!("t * {{module}} * {k}");
    let fy = format!("({{{p}r}} + {{{p}bc}} * {k})");
    let r_fil = format!("hypot({fx}, {fy})");
    let a_fil = format!("{{{p}th0}} + t * {{module}} / {{{p}r}} * 1 rad - atan({fx} / {fy})");
    let (f0, f1) = fillet_range;
    let curves = vec![
        polar_curve("lower fillet", &r_fil, &a_fil, &ph, -1.0, f0.clone(), f1.clone(), tol_fillet),
        polar_curve("lower flank", &r_inv, &a_inv, &ph, -1.0, flank_start.clone(), format!("{{{p}u1}}"), tol_flank),
        polar_curve("upper flank", &r_inv, &a_inv, &ph, 1.0, flank_start, format!("{{{p}u1}}"), tol_flank),
        polar_curve("upper fillet", &r_fil, &a_fil, &ph, 1.0, f0, f1, tol_fillet),
    ];
    let half_pitch = format!("pi / {{{teeth}}} * 1 rad");
    let points = vec![polar_point(&format!("{{{p}rf}}"), &half_pitch, &ph, -1.0), polar_point(&format!("{{{p}rf}}"), &half_pitch, &ph, 1.0)];
    let edges = vec![Edge::Arc(End::Point(0), End::Start(0)), Edge::Arc(End::End(1), End::End(2)), Edge::Arc(End::Start(3), End::Point(1))];
    let joins = if exact { vec![(End::End(0), End::Start(1)), (End::End(3), End::Start(2))] } else { Vec::new() };
    // Undercut: the same curves over formula ranges, for teeth that follow parameter changes
    // (the fillet's end meets the flank's start by their formulas where the form circle is
    // above the base circle; else the flank from the base circle, crossing the fillet).
    let following = (!exact).then(|| {
        let (start, joins) = if u0 >= 0.0 {
            (format!("{{{p}u0}}"), vec![(End::End(0), End::Start(1)), (End::End(3), End::Start(2))])
        } else {
            (String::from("0"), Vec::new())
        };
        let end = format!("{{{p}tf}}");
        let curves = vec![
            polar_curve("lower fillet", &r_fil, &a_fil, &ph, -1.0, "0".into(), end.clone(), tol_fillet),
            polar_curve("lower flank", &r_inv, &a_inv, &ph, -1.0, start.clone(), format!("{{{p}u1}}"), tol_flank),
            polar_curve("upper flank", &r_inv, &a_inv, &ph, 1.0, start, format!("{{{p}u1}}"), tol_flank),
            polar_curve("upper fillet", &r_fil, &a_fil, &ph, 1.0, "0".into(), end, tol_fillet),
        ];
        (curves, joins)
    });
    Ok(ToothCell {
        who: src.who.clone(),
        member: src.member,
        curves,
        points,
        edges,
        joins,
        repeat: Repeat::Circular { count: format!("{{{teeth}}}") },
        closing: Vec::new(),
        exact,
        following,
        face_key: src.face_key.clone(),
        helix_key: c.helix.clone(),
        radius_key: Some(format!("{p}r")),
        module: m,
        vars: v,
    })
}

/// Where the fillet (from `t` = 0) reaches radius `h`, and the involute's roll there, refined
/// so the two points meet: (fillet t, involute roll).
fn crossing(v: &Vars, p: &str, h: f64, tf: f64) -> Option<(f64, f64)> {
    let hb_key = format!("{p}hb");
    let rb = v.value(&format!("{p}rb"))?;
    let radius = |t: f64| fillet_at(v, p, t).map(|q| q.len());
    // Bracket: the fillet's radius grows from the root; search out to well past `tf`.
    let mut hi = tf.max(0.1);
    let mut tries = 0;
    while radius(hi)? < h {
        hi *= 1.5;
        tries += 1;
        if tries > 40 {
            return None;
        }
    }
    let (mut lo, mut up) = (0.0, hi);
    for _ in 0..200 {
        let mid = 0.5 * (lo + up);
        if radius(mid)? < h {
            lo = mid;
        } else {
            up = mid;
        }
    }
    let mut t = 0.5 * (lo + up);
    let mut u = ((h / rb).powi(2) - 1.0).max(0.0).sqrt();
    // Newton on the two points meeting (fillet(t) = involute(u)).
    for _ in 0..30 {
        let a = fillet_at(v, p, t)?;
        let b = involute_at(v, p, &hb_key, u)?;
        let d = a - b;
        if d.len() < 1e-13 * h.max(1.0) {
            break;
        }
        let e = 1e-7;
        let da = (fillet_at(v, p, t + e)? - a) * (1.0 / e);
        let db = (involute_at(v, p, &hb_key, u + e)? - b) * (1.0 / e);
        // d + da·dt − db·du = 0
        let det = da.x * (-db.y) - (-db.x) * da.y;
        if det.abs() < 1e-300 {
            break;
        }
        let dt = (-d.x * (-db.y) - (-db.x) * (-d.y)) / det;
        let du = (da.x * (-d.y) - (-d.x) * da.y) / det;
        t += dt;
        u += du;
        if !(t.is_finite() && u.is_finite()) {
            return None;
        }
    }
    (t >= 0.0).then_some((t, u))
}

/// The cell of a ring gear (its tooth spaces as teeth), space 0 at `phase`.
fn internal(src: &TeethSource, ring: &Internal, f: &ToothFlank, phase: f64) -> Result<ToothCell, String> {
    let g = &ring.gear;
    if f.flank.len() < 2 || f.defect().is_some() || f.tip_half <= 1e-9 {
        return Err("the ring's spaces have no flank of their own".into());
    }
    let mut v = Vars::default();
    let c = common(&mut v, src, g)?;
    let (p, mt, at, teeth, shift, bl) = (&c.p, &c.mt, &c.at, c.teeth, c.shift, &c.bl);
    let m = g.module;
    let ha = number(g.rack.addendum);
    let hf = number(g.rack.dedendum);
    let mut exact = true;
    let rr = v.derived(&format!("{p}rr"), format!("{{{p}r}} + ({hf} + {{{shift}}}) * {{module}}"), Quantity::Length, "root radius (outer)")?;
    let rr_key = if (rr - f.ra).abs() > 1e-9 * rr.max(1.0) {
        exact = false;
        literal(f.ra, Quantity::Length)
    } else {
        format!("{{{p}rr}}")
    };
    let standard = g.r() - (g.rack.addendum - g.shift) * m;
    let ts = if g.tip_shortening.abs() > 1e-12 { format!(" + {}", literal(g.tip_shortening, Quantity::Length)) } else { String::new() };
    let rt_formula = if standard > 0.0 {
        format!(
            "max({{{p}r}} - ({ha} - {{{shift}}}) * {{module}}, hypot({{{p}rb}}, max({{{p}r}} * sin({at}) - ({ha} - {{{shift}}}) * {{module}} / sin({at}), 0 mm))){ts}"
        )
    } else {
        format!("{{{p}r}} - ({ha} - {{{shift}}}) * {{module}}{ts}")
    };
    let rt = v.derived(&format!("{p}rt"), rt_formula, Quantity::Length, "tip radius (inner)")?;
    let rt_key = if (rt - f.rf).abs() > 1e-9 * rt.max(1.0) {
        exact = false;
        literal(f.rf, Quantity::Length)
    } else {
        format!("{{{p}rt}}")
    };
    v.derived(
        &format!("{p}hs"),
        format!("(pi * {mt} / 2 + 2 * {{{shift}}} * {{module}} * tan({at}) + {bl}) / (2 * {{{p}r}}) * 1 rad + tan({at}) * 1 rad - {at}"),
        Quantity::Angle,
        "half the tooth space's angle at the base circle",
    )?;
    let rb = g.rb();
    let radial = f.rf < rb;
    let ulo = if radial { "0".to_string() } else { format!("sqrt(({rt_key} / {{{p}rb}}) ^ 2 - 1)") };
    let uhi = format!("sqrt(({rr_key} / {{{p}rb}}) ^ 2 - 1)");
    let (tol_flank, _) = tolerances(m);
    let ph = phase_text(&mut v, src, phase, g.teeth)?;
    let r_inv = format!("{{{p}rb}} * sqrt(1 + t ^ 2)");
    let a_inv = format!("{{{p}hs}} - t * 1 rad + atan(t)");
    let curves = vec![
        polar_curve("lower flank", &r_inv, &a_inv, &ph, -1.0, ulo.clone(), uhi.clone(), tol_flank),
        polar_curve("upper flank", &r_inv, &a_inv, &ph, 1.0, ulo, uhi, tol_flank),
    ];
    let half_pitch = format!("pi / {{{teeth}}} * 1 rad");
    let mut points = vec![polar_point(&rt_key, &half_pitch, &ph, -1.0), polar_point(&rt_key, &half_pitch, &ph, 1.0)];
    let mut edges = Vec::new();
    if radial {
        let hs = format!("{{{p}hs}}");
        points.push(polar_point(&rt_key, &hs, &ph, -1.0));
        points.push(polar_point(&rt_key, &hs, &ph, 1.0));
        edges.push(Edge::Arc(End::Point(0), End::Point(2)));
        edges.push(Edge::Line(End::Point(2), End::Start(0)));
        edges.push(Edge::Arc(End::End(0), End::End(1)));
        edges.push(Edge::Line(End::Start(1), End::Point(3)));
        edges.push(Edge::Arc(End::Point(3), End::Point(1)));
    } else {
        edges.push(Edge::Arc(End::Point(0), End::Start(0)));
        edges.push(Edge::Arc(End::End(0), End::End(1)));
        edges.push(Edge::Arc(End::Start(1), End::Point(1)));
    }
    Ok(ToothCell {
        who: src.who.clone(),
        member: src.member,
        curves,
        points,
        edges,
        joins: Vec::new(),
        repeat: Repeat::Circular { count: format!("{{{teeth}}}") },
        closing: Vec::new(),
        exact,
        following: None,
        face_key: src.face_key.clone(),
        helix_key: c.helix.clone(),
        radius_key: Some(format!("{p}r")),
        module: m,
        vars: v,
    })
}

/// The cell of a straight rack: one tooth from x = 0 to one pitch, repeated along +x, and the
/// back below.
fn rack(src: &TeethSource, g: &Involute, count: u32, below: f64) -> Result<ToothCell, String> {
    let mut v = Vars::default();
    v.input("module", g.module, Quantity::Length, "normal module");
    v.input("pressure_angle", g.pressure_angle, Quantity::Angle, "normal pressure angle");
    v.input("rack_teeth", f64::from(count), Quantity::Number, "rack: number of teeth");
    v.input("shift", g.shift, Quantity::Number, "rack: profile shift coefficient");
    v.input("backlash", src.backlash, Quantity::Length, "backlash at the pitch line");
    v.input(&src.face_key, src.face, Quantity::Length, "face width");
    v.input("rack_height", below, Quantity::Length, "rack: height below the pitch line");
    let p = "rack_";
    let (mt, at) = if g.helix != 0.0 {
        v.input("helix", g.helix.abs(), Quantity::Angle, "helix angle");
        v.derived("rack_mt", "{module} / cos({helix})".into(), Quantity::Length, "transverse module")?;
        v.derived("rack_at", "atan(tan({pressure_angle}) / cos({helix}))".into(), Quantity::Angle, "transverse pressure angle")?;
        ("{rack_mt}".to_string(), "{rack_at}".to_string())
    } else {
        ("{module}".to_string(), "{pressure_angle}".to_string())
    };
    let extra = g.backlash - src.backlash;
    let bl = if extra.abs() > 1e-12 { format!("({{backlash}} + {})", literal(extra, Quantity::Length)) } else { "{backlash}".to_string() };
    let ts = if g.tip_shortening.abs() > 1e-12 { format!(" - {}", literal(g.tip_shortening, Quantity::Length)) } else { String::new() };
    let pitch = v.derived(&format!("{p}p"), format!("pi * {mt}"), Quantity::Length, "pitch")?;
    v.derived(
        &format!("{p}s"),
        format!("{{{p}p}} / 2 + 2 * {{shift}} * {{module}} * tan({at}) - {bl}"),
        Quantity::Length,
        "tooth thickness on the pitch line",
    )?;
    v.derived(&format!("{p}ha"), format!("({} + {{shift}}) * {{module}}{ts}", number(g.rack.addendum)), Quantity::Length, "addendum")?;
    v.derived(&format!("{p}hf"), format!("({} - {{shift}}) * {{module}}", number(g.rack.dedendum)), Quantity::Length, "dedendum")?;
    let ht = v.derived(&format!("{p}ht"), format!("max({{{p}s}} / 2 - {{{p}ha}} * tan({at}), 0 mm)"), Quantity::Length, "half the tip land")?;
    let hr = v.derived(
        &format!("{p}hr"),
        format!("min({{{p}s}} / 2 + {{{p}hf}} * tan({at}), {{{p}p}} / 2)"),
        Quantity::Length,
        "half the tooth at the root",
    )?;
    let c = "{rack_p} / 2";
    let mut points = vec![
        ["0 mm".to_string(), "-{rack_hf}".to_string()],
        [format!("{c} - {{rack_hr}}"), "-{rack_hf}".to_string()],
        [format!("{c} - {{rack_ht}}"), "{rack_ha}".to_string()],
        [format!("{c} + {{rack_ht}}"), "{rack_ha}".to_string()],
        [format!("{c} + {{rack_hr}}"), "-{rack_hf}".to_string()],
        ["{rack_p}".to_string(), "-{rack_hf}".to_string()],
    ];
    let flat_root = hr < pitch / 2.0 - 1e-9;
    let land = ht > 1e-9;
    let mut edges = Vec::new();
    if flat_root {
        edges.push(Edge::Line(End::Point(0), End::Point(1)));
    }
    edges.push(Edge::Line(End::Point(1), End::Point(2)));
    if land {
        edges.push(Edge::Line(End::Point(2), End::Point(3)));
        edges.push(Edge::Line(End::Point(3), End::Point(4)));
    } else {
        edges.push(Edge::Line(End::Point(2), End::Point(4)));
    }
    if flat_root {
        edges.push(Edge::Line(End::Point(4), End::Point(5)));
    }
    // The back: from the end of the last tooth down, along and up to the start.
    let first = if flat_root { 0 } else { 1 };
    points.push(["{rack_p} * {rack_teeth}".into(), "-{rack_hf}".into()]);
    points.push(["{rack_p} * {rack_teeth}".into(), "-{rack_height}".into()]);
    points.push(["0 mm".into(), "-{rack_height}".into()]);
    let n = points.len();
    // (Without a flat root the first tooth starts at x = 0 itself: point 1 is that corner.)
    let closing = vec![
        Edge::Line(End::Point(n - 3), End::Point(n - 2)),
        Edge::Line(End::Point(n - 2), End::Point(n - 1)),
        Edge::Line(End::Point(n - 1), End::Point(first)),
    ];
    Ok(ToothCell {
        who: src.who.clone(),
        member: src.member,
        curves: Vec::new(),
        points,
        edges,
        joins: Vec::new(),
        repeat: Repeat::Linear { count: "{rack_teeth}".into(), spacing: "{rack_p}".into() },
        closing,
        exact: true,
        following: None,
        face_key: src.face_key.clone(),
        helix_key: None,
        radius_key: None,
        module: g.module,
        vars: v,
    })
}

// ---------------------------------------------------------------------------------------------
// Evaluating a cell (for checks against the outline it stands for, and tests).
// ---------------------------------------------------------------------------------------------

impl ToothCell {
    /// Curve `i` at parameter `t`.
    pub fn curve_at(&self, i: usize, t: f64) -> Result<V2, String> {
        let c = self.curves.get(i).ok_or("no such curve")?;
        Ok(V2::new(self.vars.eval(&c.x, Some(t))?, self.vars.eval(&c.y, Some(t))?))
    }
    /// Curve `i`'s parameter range.
    pub fn range(&self, i: usize) -> Result<(f64, f64), String> {
        let c = self.curves.get(i).ok_or("no such curve")?;
        Ok((self.vars.eval(&c.start, None)?, self.vars.eval(&c.end, None)?))
    }
    pub fn point(&self, i: usize) -> Result<V2, String> {
        let p = self.points.get(i).ok_or("no such point")?;
        Ok(V2::new(self.vars.eval(&p[0], None)?, self.vars.eval(&p[1], None)?))
    }
    pub fn end(&self, e: &End) -> Result<V2, String> {
        match e {
            End::Start(i) => self.curve_at(*i, self.range(*i)?.0),
            End::End(i) => self.curve_at(*i, self.range(*i)?.1),
            End::Point(i) => self.point(*i),
        }
    }
    /// The pattern's count.
    pub fn count(&self) -> Result<usize, String> {
        let tpl = match &self.repeat {
            Repeat::Circular { count } | Repeat::Linear { count, .. } => count,
        };
        let n = self.vars.eval(tpl, None)?;
        Ok(n.round().max(0.0) as usize)
    }
    /// Every template the cell draws with (for checking it renders).
    pub fn templates(&self) -> Vec<&str> {
        let mut out: Vec<&str> = Vec::new();
        for c in &self.curves {
            out.extend([c.x.as_str(), c.y.as_str(), c.start.as_str(), c.end.as_str()]);
        }
        for p in &self.points {
            out.extend([p[0].as_str(), p[1].as_str()]);
        }
        match &self.repeat {
            Repeat::Circular { count } => out.push(count),
            Repeat::Linear { count, spacing } => out.extend([count.as_str(), spacing.as_str()]),
        }
        out
    }
}

// ---------------------------------------------------------------------------------------------
// Finding the cell an outline stands for.
// ---------------------------------------------------------------------------------------------

fn close(a: V2, b: V2, tol: f64) -> bool {
    a.dist(b) <= tol
}

/// The teeth of flank `f` (`n` of them) that `o` is, and tooth 0's phase.
fn teeth_phase(f: &ToothFlank, n: u32, o: &Outline) -> Option<f64> {
    if n == 0 || o.segs.is_empty() {
        return None;
    }
    let p0 = o.segs[0].start();
    let phase = p0.angle() + f.root_half;
    let reference = teeth_outline(f, n, phase);
    if reference.segs.len() != o.segs.len() {
        return None;
    }
    let tol = 1e-7 * f.ra.abs().max(1.0);
    let same = reference
        .segs
        .iter()
        .zip(&o.segs)
        .all(|(a, b)| std::mem::discriminant(a) == std::mem::discriminant(b) && close(a.start(), b.start(), tol) && close(a.end(), b.end(), tol));
    same.then_some(phase)
}

/// Does the cell's tooth 0 run where the outline's does? Compares the curves' and arcs' ends
/// with the outline's pieces, in order.
fn cell_matches(cell: &ToothCell, o: &Outline, per_tooth: usize) -> bool {
    let tol = 1e-6 * cell.module.max(1e-3);
    // The outline's tooth 0: its pieces' ends in order, the root arc's start last.
    let ends: Vec<(V2, V2)> = o.segs.iter().take(per_tooth).map(|s| (s.start(), s.end())).collect();
    let mut want: Vec<(V2, V2)> = Vec::new();
    for e in &cell.edges {
        let (a, b) = match e {
            Edge::Line(a, b) | Edge::Arc(a, b) => (a, b),
        };
        let (Ok(a), Ok(b)) = (cell.end(a), cell.end(b)) else { return false };
        want.push((a, b));
    }
    for i in 0..cell.curves.len() {
        let (Ok(a), Ok(b)) = (cell.end(&End::Start(i)), cell.end(&End::End(i))) else { return false };
        want.push((a, b));
    }
    // Every outline piece but the root arc is one of the cell's pieces (either way round); the
    // root arc runs from the last piece's end to the next tooth.
    ends.iter()
        .take(per_tooth.saturating_sub(1))
        .all(|(a, b)| want.iter().any(|(c, d)| (close(*a, *c, tol) && close(*b, *d, tol)) || (close(*a, *d, tol) && close(*b, *c, tol))))
}

/// The formulas for an outline of a planned set: the cell of whichever source made it (tooth 0
/// where the outline puts it), or `None` (not teeth, or teeth the formulas can't follow: tip
/// relief, tip rounding, a tip lowered to keep a land, more than 500 teeth).
pub fn cell_for(sources: &[TeethSource], o: &Outline) -> Option<ToothCell> {
    for src in sources {
        let found = match &src.form {
            Form::External { g, f } => {
                let Some(phase) = teeth_phase(f, g.teeth, o) else { continue };
                let per = o.segs.len() / g.teeth.max(1) as usize;
                external(src, g, f, phase).ok().filter(|c| cell_matches(c, o, per))
            }
            Form::Internal { ring, f } => {
                let Some(phase) = teeth_phase(f, ring.gear.teeth, o) else { continue };
                let per = o.segs.len() / ring.gear.teeth.max(1) as usize;
                internal(src, ring, f, phase).ok().filter(|c| cell_matches(c, o, per))
            }
            Form::Rack { g, count, below } => {
                if rack_outline(g, *count, *below) != *o {
                    continue;
                }
                rack(src, g, *count, *below).ok()
            }
        };
        if let Some(c) = found.filter(|c| c.count().is_ok_and(|n| (1..=500).contains(&n))) {
            return Some(c);
        }
    }
    None
}

/// The cell of a source at a phase (tooth 0's angle), whatever outline it would match: for
/// tests and previews.
pub fn cell_of(src: &TeethSource, phase: f64) -> Result<ToothCell, String> {
    match &src.form {
        Form::External { g, f } => external(src, g, f, phase),
        Form::Internal { ring, f } => internal(src, ring, f, phase),
        Form::Rack { g, count, below } => rack(src, g, *count, *below),
    }
}

/// The edges of a cell as plain segments (tooth 0), for checks.
pub fn cell_segments(cell: &ToothCell) -> Result<Vec<Seg>, String> {
    let mut out = Vec::new();
    for e in cell.edges.iter().chain(&cell.closing) {
        match e {
            Edge::Line(a, b) => out.push(Seg::Line(cell.end(a)?, cell.end(b)?)),
            Edge::Arc(a, b) => out.push(Seg::Arc { c: V2::ZERO, a: cell.end(a)?, b: cell.end(b)?, ccw: true }),
        }
    }
    Ok(out)
}

//! Gear teeth as formulas: one tooth of an involute gear (or one tooth space of a ring gear, or
//! one tooth of a rack) as curves of a parameter `t` in the design's expression language, with the
//! arcs and lines between them, for a CAD sketch that draws equation curves and repeats the tooth
//! with a pattern. The formulas are the gear's own: the involute from the base circle, the root
//! fillet as the trochoid the rack cutter's tip fillet generates, tip and root on their circles.
//!
//! Every number a formula needs is a [`Var`]: the inputs (module, tooth count, pressure angle,
//! profile shift, backlash, face width) and quantities derived from them (pitch, base, tip and
//! root radii, the cutter's fillet centre, the curves' parameter ranges). Formulas name them as
//! `{key}`; [`render`] puts in either design parameter names (so the teeth follow parameter
//! edits) or the numbers themselves.
//!
//! What follows a parameter change exactly: a gear without undercut, its pointed-tip and
//! raised-tip limits not reached. An undercut gear's fillet meets its involute where the two
//! cross, which no closed formula gives: those two curves get numeric ranges, worked out here
//! ([`ToothCell::exact`] is false), and follow parameter changes only approximately.

use std::f64::consts::PI;

use crate::geom::{Outline, Seg, V2};
use crate::involute::{FILLET_TOLERANCE, Internal, Involute, PROFILE_TOLERANCE, ToothFlank, rack_outline, teeth_outline};

// ---------------------------------------------------------------------------------------------
// Where teeth come from: what the plan records for each toothed member.
// ---------------------------------------------------------------------------------------------

/// How a member's teeth were made.
#[derive(Clone, Debug, PartialEq)]
pub enum Form {
    /// External teeth generated by the rack cutter: `f` is [`crate::involute::external_flank`]
    /// of `g` (tuned or not: a tuned flank simply finds no formulas).
    External { g: Involute, f: ToothFlank },
    /// A ring gear's teeth: `f` is the tooth spaces' flank ([`Internal::space_flank`]).
    Internal { ring: Internal, f: ToothFlank },
    /// A straight rack ([`rack_outline`]).
    Rack { g: Involute, count: u32, below: f64 },
}

/// One toothed member of a planned set, for [`cell_for`].
#[derive(Clone, Debug, PartialEq)]
pub struct TeethSource {
    /// The member as warnings name it ("gear 1", "planet", "ring"…).
    pub who: String,
    /// Which tooth count and shift inputs drive it: 1 (`teeth`, `shift`), 2 (`teeth2`,
    /// `shift2`) or 3 (`teeth3`, `shift3`).
    pub member: u8,
    pub form: Form,
    /// The set's own backlash (mm): the member's flank may be thinner by more (its own
    /// backlash, a printer's horizontal compensation), which stays a number.
    pub backlash: f64,
    /// The member's face width (mm) and its input's key (`face_width`, or `face_width2` for a
    /// mate of another width).
    pub face: f64,
    pub face_key: String,
    /// Tooth 0's angle as formulas, where the set can give it (a pair's gear 2, the planets, a
    /// planetary ring): (key, template), the first whose value is the outline's phase (to a
    /// whole tooth) drawing the teeth, so a parametric set's members turn to mesh again when
    /// their tooth counts change. Otherwise the phase is a number.
    pub phases: Vec<(String, String)>,
    /// The inputs those templates name that the member's own formulas don't (the set's
    /// [`Placing::vars`]).
    pub extra: Vars,
}

// ---------------------------------------------------------------------------------------------
// Variables and formulas.
// ---------------------------------------------------------------------------------------------

/// What a variable measures.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Quantity {
    Length,
    Angle,
    Number,
}

/// A number the formulas use.
#[derive(Clone, Debug, PartialEq)]
pub struct Var {
    /// The name formulas give it (`{key}`); a design parameter is named `<prefix>_<key>`.
    pub key: String,
    /// An input's value as a design parameter's expression ("2 mm", "20 deg", "20"); a derived
    /// quantity's formula over other variables.
    pub expr: String,
    /// The value, in mm, radians or plain.
    pub value: f64,
    pub quantity: Quantity,
    /// One of the gear's inputs (module, teeth…) rather than worked out from them.
    pub input: bool,
    pub comment: String,
}

/// A number as the expression language reads it (negative numbers in brackets).
pub fn number(v: f64) -> String {
    let v = if v == 0.0 { 0.0 } else { v };
    if v < 0.0 { format!("({v})") } else { format!("{v}") }
}

/// A value of a quantity as a literal: "2.5 mm", "0.349 rad", "20".
pub fn literal(v: f64, q: Quantity) -> String {
    let v = if v == 0.0 { 0.0 } else { v };
    let unit = match q {
        Quantity::Length => " mm",
        Quantity::Angle => " rad",
        Quantity::Number => "",
    };
    if v < 0.0 { format!("({v}{unit})") } else { format!("{v}{unit}") }
}

/// An input's value as a parameter's expression: angles in degrees.
fn input_literal(v: f64, q: Quantity) -> String {
    match q {
        Quantity::Angle => format!("{} deg", number(v.to_degrees())),
        _ => literal(v, q),
    }
}

/// `tpl` with every `{key}` replaced by `name(key)`.
pub fn render(tpl: &str, name: &dyn Fn(&str) -> String) -> String {
    let mut out = String::with_capacity(tpl.len() + 32);
    let mut rest = tpl;
    while let Some(i) = rest.find('{') {
        out.push_str(&rest[..i]);
        let after = &rest[i + 1..];
        match after.find('}') {
            Some(j) => {
                out.push_str(&name(&after[..j]));
                rest = &after[j + 1..];
            }
            None => {
                out.push_str(&rest[i..]);
                rest = "";
            }
        }
    }
    out.push_str(rest);
    out
}

/// The keys a template names.
pub fn keys(tpl: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = tpl;
    while let Some(i) = rest.find('{') {
        let after = &rest[i + 1..];
        let Some(j) = after.find('}') else { break };
        let k = after[..j].to_string();
        if !out.contains(&k) {
            out.push(k);
        }
        rest = &after[j + 1..];
    }
    out
}

/// The variables of one member, in order (each only uses the ones before it).
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Vars {
    pub list: Vec<Var>,
}

impl Vars {
    pub fn get(&self, key: &str) -> Option<&Var> {
        self.list.iter().find(|v| v.key == key)
    }
    pub fn value(&self, key: &str) -> Option<f64> {
        self.get(key).map(|v| v.value)
    }
    pub(crate) fn input(&mut self, key: &str, value: f64, quantity: Quantity, comment: &str) {
        if self.get(key).is_none() {
            self.list.push(Var { key: key.into(), expr: input_literal(value, quantity), value, quantity, input: true, comment: comment.into() });
        }
    }
    /// Adds a derived variable; its value is its formula's.
    pub(crate) fn derived(&mut self, key: &str, expr: String, quantity: Quantity, comment: &str) -> Result<f64, String> {
        let value = self.eval(&expr, None).map_err(|e| format!("{key}: {e}"))?;
        if !value.is_finite() {
            return Err(format!("{key} is not a number"));
        }
        self.list.push(Var { key: key.into(), expr, value, quantity, input: false, comment: comment.into() });
        Ok(value)
    }
    /// A template's value, `t` the curve parameter.
    pub fn eval(&self, tpl: &str, t: Option<f64>) -> Result<f64, String> {
        eval(tpl, &|k| if k == "t" { t } else { self.value(k) })
    }
    /// A template with the variables put in as numbers.
    pub fn numeric(&self, tpl: &str) -> String {
        render(tpl, &|k| match self.get(k) {
            Some(v) => literal(v.value, v.quantity),
            None => format!("{{{k}}}"),
        })
    }
}

/// One curve of a tooth: `x(t)`, `y(t)` for `t` from `start` to `end` (templates).
#[derive(Clone, Debug, PartialEq)]
pub struct Curve {
    /// What it is ("lower fillet", "upper flank"…).
    pub name: String,
    pub x: String,
    pub y: String,
    pub start: String,
    pub end: String,
    /// How far the sketch's spline may stray from the formulas (mm).
    pub tolerance: f64,
}

/// An end of an edge.
#[derive(Clone, Debug, PartialEq)]
pub enum End {
    /// Where curve `i` starts or ends.
    Start(usize),
    End(usize),
    /// Point `i` of [`ToothCell::points`].
    Point(usize),
}

/// A straight or circular edge between two ends.
#[derive(Clone, Debug, PartialEq)]
pub enum Edge {
    Line(End, End),
    /// About the origin, counter-clockwise from the first end to the second.
    Arc(End, End),
}

/// How the tooth is repeated.
#[derive(Clone, Debug, PartialEq)]
pub enum Repeat {
    /// Round the origin, `count` times in all (a template).
    Circular { count: String },
    /// Along +x, `count` times `spacing` apart (templates).
    Linear { count: String, spacing: String },
}

/// One tooth with everything needed to draw the whole outline.
#[derive(Clone, Debug, PartialEq)]
pub struct ToothCell {
    pub who: String,
    pub member: u8,
    pub vars: Vars,
    pub curves: Vec<Curve>,
    /// Points placed by formulas (x, y templates).
    pub points: Vec<[String; 2]>,
    /// The tooth's edges: lines and arcs between curve ends and points.
    pub edges: Vec<Edge>,
    /// Ends that meet exactly by their formulas (to be made coincident).
    pub joins: Vec<(End, End)>,
    pub repeat: Repeat,
    /// Edges drawn once, outside the pattern (a rack's back), and their points' indices are
    /// into `points` as well.
    pub closing: Vec<Edge>,
    /// Every curve range is a formula: the teeth follow any parameter change that keeps the same
    /// pieces. False for an undercut gear (numeric fillet/flank ranges) or a tip or root limit
    /// reached (a numeric radius).
    pub exact: bool,
    /// An undercut gear's teeth for parameters that change: its curves (and joins) with every
    /// range a formula (the whole fillet, the flank from its form circle), so after a change
    /// the fillet and the flank still cross where they now do, and the extrusion takes the
    /// gear's own region between the small loops. `None` for an exact cell.
    pub following: Option<(Vec<Curve>, Vec<(End, End)>)>,
    /// The keys of the face width and helix inputs and of the pitch radius, for extrusions
    /// and twists (helix: none for straight teeth).
    pub face_key: String,
    pub helix_key: Option<String>,
    pub radius_key: Option<String>,
    pub module: f64,
}

// ---------------------------------------------------------------------------------------------
// A small evaluator for the templates (the design's expression language, without unit checks:
// mm, rad and deg read as 1, 1 and π/180).
// ---------------------------------------------------------------------------------------------

struct Parser<'a> {
    s: &'a [u8],
    i: usize,
    look: &'a dyn Fn(&str) -> Option<f64>,
}

impl Parser<'_> {
    fn ws(&mut self) {
        while self.i < self.s.len() && self.s[self.i].is_ascii_whitespace() {
            self.i += 1;
        }
    }
    fn peek(&mut self) -> Option<u8> {
        self.ws();
        self.s.get(self.i).copied()
    }
    fn ident(&mut self) -> String {
        self.ws();
        let start = self.i;
        while self.i < self.s.len() && (self.s[self.i].is_ascii_alphanumeric() || self.s[self.i] == b'_') {
            self.i += 1;
        }
        String::from_utf8_lossy(&self.s[start..self.i]).into_owned()
    }
    fn expr(&mut self) -> Result<f64, String> {
        let mut v = self.term()?;
        loop {
            match self.peek() {
                Some(b'+') => {
                    self.i += 1;
                    v += self.term()?;
                }
                Some(b'-') => {
                    self.i += 1;
                    v -= self.term()?;
                }
                _ => return Ok(v),
            }
        }
    }
    fn term(&mut self) -> Result<f64, String> {
        let mut v = self.unary()?;
        loop {
            match self.peek() {
                Some(b'*') => {
                    self.i += 1;
                    v *= self.unary()?;
                }
                Some(b'/') => {
                    self.i += 1;
                    v /= self.unary()?;
                }
                _ => return Ok(v),
            }
        }
    }
    fn unary(&mut self) -> Result<f64, String> {
        if self.peek() == Some(b'-') {
            self.i += 1;
            return Ok(-self.unary()?);
        }
        let base = self.primary()?;
        if self.peek() == Some(b'^') {
            self.i += 1;
            let e = self.unary()?;
            return Ok(base.powf(e));
        }
        Ok(base)
    }
    fn unit(&mut self) -> f64 {
        let save = self.i;
        let id = self.ident();
        match id.as_str() {
            "mm" | "rad" => 1.0,
            "deg" => PI / 180.0,
            _ => {
                self.i = save;
                1.0
            }
        }
    }
    fn primary(&mut self) -> Result<f64, String> {
        match self.peek() {
            Some(b'(') => {
                self.i += 1;
                let v = self.expr()?;
                if self.peek() != Some(b')') {
                    return Err("missing )".into());
                }
                self.i += 1;
                Ok(v)
            }
            Some(b'{') => {
                self.i += 1;
                let start = self.i;
                while self.i < self.s.len() && self.s[self.i] != b'}' {
                    self.i += 1;
                }
                let key = String::from_utf8_lossy(&self.s[start..self.i]).into_owned();
                self.i += 1;
                (self.look)(&key).ok_or_else(|| format!("unknown `{key}`"))
            }
            Some(c) if c.is_ascii_digit() || c == b'.' => {
                let start = self.i;
                while self.i < self.s.len() && (self.s[self.i].is_ascii_digit() || self.s[self.i] == b'.') {
                    self.i += 1;
                }
                if self.i < self.s.len() && (self.s[self.i] == b'e' || self.s[self.i] == b'E') {
                    let mark = self.i;
                    self.i += 1;
                    if self.i < self.s.len() && (self.s[self.i] == b'-' || self.s[self.i] == b'+') {
                        self.i += 1;
                    }
                    if self.i < self.s.len() && self.s[self.i].is_ascii_digit() {
                        while self.i < self.s.len() && self.s[self.i].is_ascii_digit() {
                            self.i += 1;
                        }
                    } else {
                        self.i = mark;
                    }
                }
                let v: f64 = std::str::from_utf8(&self.s[start..self.i]).ok().and_then(|t| t.parse().ok()).ok_or("bad number")?;
                Ok(v * self.unit())
            }
            Some(_) => {
                let id = self.ident();
                if id.is_empty() {
                    return Err(format!("unexpected text at {}", self.i));
                }
                if self.peek() == Some(b'(') {
                    self.i += 1;
                    let mut args = vec![self.expr()?];
                    while self.peek() == Some(b',') {
                        self.i += 1;
                        args.push(self.expr()?);
                    }
                    if self.peek() != Some(b')') {
                        return Err("missing )".into());
                    }
                    self.i += 1;
                    let a = args[0];
                    let b = args.get(1).copied();
                    return Ok(match (id.as_str(), b) {
                        ("sin", None) => a.sin(),
                        ("cos", None) => a.cos(),
                        ("tan", None) => a.tan(),
                        ("atan", None) => a.atan(),
                        ("acos", None) => a.acos(),
                        ("asin", None) => a.asin(),
                        ("sqrt", None) => a.sqrt(),
                        ("abs", None) => a.abs(),
                        ("atan2", Some(b)) => a.atan2(b),
                        ("hypot", Some(b)) => a.hypot(b),
                        ("round", None) => a.round(),
                        ("floor", None) => a.floor(),
                        ("ceil", None) => a.ceil(),
                        ("mod", Some(b)) => a.rem_euclid(b),
                        ("min", Some(_)) => args.iter().copied().fold(f64::INFINITY, f64::min),
                        ("max", Some(_)) => args.iter().copied().fold(f64::NEG_INFINITY, f64::max),
                        _ => return Err(format!("unknown function `{id}`")),
                    });
                }
                match id.as_str() {
                    "pi" | "PI" => Ok(PI),
                    _ => (self.look)(&id).ok_or_else(|| format!("unknown `{id}`")),
                }
            }
            None => Err("unexpected end".into()),
        }
    }
}

/// The value of a template or expression; `look` gives `{key}`s and bare names (`t`).
pub fn eval(text: &str, look: &dyn Fn(&str) -> Option<f64>) -> Result<f64, String> {
    let mut p = Parser { s: text.as_bytes(), i: 0, look };
    let v = p.expr()?;
    if p.peek().is_some() {
        return Err(format!("unexpected text at {} in `{text}`", p.i));
    }
    Ok(v)
}


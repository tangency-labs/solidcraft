//! Generates `$OUT_DIR/units.rs`: one `mod` per `src/units/*.rs` file plus
//! `fn registered() -> Vec<Box<dyn UnitDiff>>` constructing each file's
//! `Runner`. Adding a runner therefore never edits a shared file.
//! Runner modules are only compiled with feature `cpp` (they call into
//! `solidcore_ffi::units`, which only exists then).
#![allow(
    clippy::expect_used,
    clippy::panic,
    clippy::unwrap_used,
    clippy::pedantic
)]

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let cpp = env::var_os("CARGO_FEATURE_CPP").is_some();
    let dir = manifest.join("src").join("units");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut files: Vec<PathBuf> = fs::read_dir(&dir)
        .map(|rd| rd.filter_map(|e| e.ok().map(|e| e.path())).collect())
        .unwrap_or_default();
    files.retain(|p| p.extension().and_then(|e| e.to_str()) == Some("rs"));
    files.sort();

    let mut src = String::from("// @generated by difftest/build.rs\n");
    let mut ctor = String::new();
    if cpp {
        for f in &files {
            let stem = f.file_stem().and_then(|s| s.to_str()).expect("utf-8 name");
            writeln!(
                src,
                "#[path = {:?}]\npub mod {stem};",
                f.display().to_string()
            )
            .unwrap();
            writeln!(ctor, "        Box::new({stem}::Runner),").unwrap();
        }
    }
    writeln!(
        src,
        "/// Every runner in `src/units/` (sorted by file name).\n\
         pub fn registered() -> Vec<Box<dyn crate::UnitDiff>> {{\n    vec![\n{ctor}    ]\n}}"
    )
    .unwrap();
    fs::write(out.join("units.rs"), src).expect("write units.rs");

    // If the kernel was linked as shared libs, let the binary find them.
    if let Ok(lib_dir) = env::var("DEP_SOLIDCORE_CPP_LIB_DIR") {
        println!("cargo:rustc-link-arg=-Wl,-rpath,{lib_dir}");
    }
}

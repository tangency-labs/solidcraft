//! Generates `$OUT_DIR/upstream_fixes.rs`, the field list of `kernel::UpstreamFixes`, from
//! `src/kernel/fixes/`: one file per flag, `<flag>.md`, holding that field's doc. The fields
//! are sorted by name. So adding or retiring a flag adds or deletes its own file and edits no
//! line another flag's change touches.
//!
//! The output defines `upstream_fix_fields!`, which `kernel.rs` calls with the struct's own
//! attributes and name; it passes them to `upstream_fixes!` with the field list:
//! `#[doc = " <line>"]` for each line of the file (`#[doc = ""]` for an empty line), as rustc
//! makes `/// <line>`, then `pub <flag>: bool,`.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// Rust's strict and reserved keywords: a field may not be named after one.
const KEYWORDS: &[&str] = &[
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "crate",
    "do", "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl",
    "in", "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
    "return", "self", "static", "struct", "super", "trait", "true", "try", "type", "typeof",
    "unsafe", "unsized", "use", "virtual", "where", "while", "yield",
];

fn main() {
    if let Err(e) = run() {
        eprintln!("error: solidcore build script: {e}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let manifest = env::var_os("CARGO_MANIFEST_DIR").ok_or("CARGO_MANIFEST_DIR is not set")?;
    let out = env::var_os("OUT_DIR").ok_or("OUT_DIR is not set")?;
    let dir = Path::new(&manifest)
        .join("src")
        .join("kernel")
        .join("fixes");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut paths: Vec<PathBuf> = Vec::new();
    for entry in fs::read_dir(&dir).map_err(|e| format!("{}: {e}", dir.display()))? {
        paths.push(entry.map_err(|e| format!("{}: {e}", dir.display()))?.path());
    }
    paths.sort();

    let mut fields = String::new();
    for path in &paths {
        println!("cargo:rerun-if-changed={}", path.display());
        let name = flag_name(path)?;
        let text = fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
        for line in doc_lines(path, &text)? {
            let doc = if line.is_empty() {
                String::new()
            } else {
                format!(" {line}")
            };
            writeln!(fields, "                #[doc = {doc:?}]").map_err(|e| e.to_string())?;
        }
        writeln!(fields, "                pub {name}: bool,").map_err(|e| e.to_string())?;
    }
    if fields.is_empty() {
        return Err(format!("{}: no flag files", dir.display()));
    }

    let src = format!(
        "// @generated by solidcore's build.rs from src/kernel/fixes/ (one file per flag, sorted by name).\n\
         macro_rules! upstream_fix_fields {{\n    \
             ($($head:tt)*) => {{\n        \
                 upstream_fixes! {{\n            \
                     $($head)*\n            {{\n{fields}            }}\n        \
                 }}\n    \
             }};\n\
         }}\n"
    );
    let path = Path::new(&out).join("upstream_fixes.rs");
    fs::write(&path, src).map_err(|e| format!("{}: {e}", path.display()))
}

/// The flag `path` declares: its file name less `.md`, which must be a lower-case Rust
/// identifier (`[a-z_][a-z0-9_]*`, not `_` and not a keyword).
fn flag_name(path: &Path) -> Result<&str, String> {
    let file = path
        .file_name()
        .and_then(|n| n.to_str())
        .ok_or_else(|| format!("{}: not a UTF-8 file name", path.display()))?;
    let name = file.strip_suffix(".md").ok_or_else(|| {
        format!(
            "{}: every file here declares one UpstreamFixes flag and is named `<flag>.md`",
            path.display()
        )
    })?;
    let mut chars = name.chars();
    let first_ok = chars
        .next()
        .is_some_and(|c| c.is_ascii_lowercase() || c == '_');
    let rest_ok = chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
    if !first_ok || !rest_ok || name == "_" || KEYWORDS.contains(&name) {
        return Err(format!(
            "{}: `{name}` is not a valid flag name (a lower-case Rust identifier: \
             [a-z_][a-z0-9_]*, not `_` and not a keyword)",
            path.display()
        ));
    }
    Ok(name)
}

/// The doc lines of a flag file: its lines, ending in one newline. A doc is required (every
/// public field has one), and carriage returns are refused so the doc is the same on every
/// checkout.
fn doc_lines<'a>(path: &Path, text: &'a str) -> Result<Vec<&'a str>, String> {
    if text.contains('\r') {
        return Err(format!(
            "{}: carriage return in a flag's doc",
            path.display()
        ));
    }
    let body = text
        .strip_suffix('\n')
        .ok_or_else(|| format!("{}: a flag's doc ends in one newline", path.display()))?;
    if body.trim().is_empty() {
        return Err(format!("{}: a flag needs its doc", path.display()));
    }
    Ok(body.split('\n').collect())
}

//! Test cases and the context used to produce them.

use std::path::{Path, PathBuf};

use serde::de::DeserializeOwned;
use serde_json::Value;

use crate::rng::{fnv1a64, Rng};
use crate::HarnessError;

/// Where a case came from (recorded in the report for reproduction).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CaseSource {
    /// `fixtures/<unit>/<file>.json`, entry `index`.
    Fixture {
        /// Repo-relative fixture path.
        path: String,
        /// Index of the case within the file.
        index: usize,
        /// Upstream test this case re-expresses, if any (e.g. `tests/prog_test/src/smCurveTest.cpp:120`).
        upstream_ref: Option<String>,
    },
    /// Generated by the unit's generator from this seed.
    Generated {
        /// Seed passed to [`Rng::new`].
        seed: u64,
    },
    /// Built in code by the runner (e.g. enumerating upstream test files).
    Inline,
}

impl CaseSource {
    /// Stable one-line description.
    pub fn describe(&self) -> String {
        match self {
            CaseSource::Fixture {
                path,
                index,
                upstream_ref,
            } => match upstream_ref {
                Some(r) => format!("fixture:{path}#{index} (upstream {r})"),
                None => format!("fixture:{path}#{index}"),
            },
            CaseSource::Generated { seed } => format!("generated:seed={seed}"),
            CaseSource::Inline => "inline".into(),
        }
    }
}

/// One input to run through both implementations.
#[derive(Debug, Clone, PartialEq)]
pub struct Case {
    /// Unit id, e.g. `nlib.knots`.
    pub unit: String,
    /// Case name, unique within the unit.
    pub name: String,
    /// Provenance.
    pub source: CaseSource,
    /// Inputs as JSON (shape defined by the unit's runner).
    pub inputs: Value,
}

impl Case {
    /// Deserialises the whole `inputs` object into the runner's input struct.
    pub fn parse<T: DeserializeOwned>(&self) -> Result<T, HarnessError> {
        serde_json::from_value(self.inputs.clone())
            .map_err(|e| HarnessError::new(format!("case {}: bad inputs: {e}", self.name)))
    }

    /// Deserialises one field of `inputs`.
    pub fn get<T: DeserializeOwned>(&self, key: &str) -> Result<T, HarnessError> {
        let v = self.inputs.get(key).ok_or_else(|| {
            HarnessError::new(format!("case {}: missing input `{key}`", self.name))
        })?;
        serde_json::from_value(v.clone())
            .map_err(|e| HarnessError::new(format!("case {}: input `{key}`: {e}", self.name)))
    }
}

/// Context for building the case list of a unit.
#[derive(Debug, Clone)]
pub struct CaseContext {
    /// Repository root.
    pub root: PathBuf,
    /// Number of generated cases per unit (`--seeds N`).
    pub seeds: usize,
}

impl CaseContext {
    /// `fixtures/<unit>/`.
    pub fn fixture_dir(&self, unit: &str) -> PathBuf {
        self.root.join("fixtures").join(unit)
    }

    /// `upstream/TestFiles/pt_TestFiles/<rel>`, checked to exist.
    pub fn upstream_test_file(&self, rel: &str) -> Result<PathBuf, HarnessError> {
        crate::fixtures::upstream_test_file(&self.root, rel)
    }

    /// All cases from `fixtures/<unit>/*.json` (files sorted by name).
    pub fn fixture_cases(&self, unit: &str) -> Result<Vec<Case>, HarnessError> {
        crate::fixtures::load_fixture_dir(&self.root, unit)
    }

    /// Seed of generated case `index` of `unit`: `fnv1a64(unit) + index`.
    pub fn seed_for(unit: &str, index: usize) -> u64 {
        fnv1a64(unit).wrapping_add(index as u64)
    }

    /// Calls `gen` with a fresh seeded [`Rng`] `self.seeds` times; stops at the
    /// first `None` (a unit without a generator returns `None` immediately).
    pub fn generated_cases(
        &self,
        unit: &str,
        mut gen: impl FnMut(&mut Rng) -> Option<Value>,
    ) -> Vec<Case> {
        let mut out = Vec::new();
        for i in 0..self.seeds {
            let seed = Self::seed_for(unit, i);
            let mut rng = Rng::new(seed);
            let Some(inputs) = gen(&mut rng) else { break };
            out.push(Case {
                unit: unit.to_string(),
                name: format!("gen{i:04}"),
                source: CaseSource::Generated { seed },
                inputs,
            });
        }
        out
    }
}

/// Repository root (two levels above this crate's manifest).
pub fn repo_root() -> PathBuf {
    let here = Path::new(env!("CARGO_MANIFEST_DIR"));
    here.parent()
        .and_then(Path::parent)
        .map_or_else(|| here.to_path_buf(), Path::to_path_buf)
}

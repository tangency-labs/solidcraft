//! WR-729 (#17902): every `blend.fillet_executive_p3` row whose mass record the exact UV
//! transpose moves, against main or against the merge base, holds both its values (main's
//! and this branch's) within the record's requested accuracy of a certified enclosure of
//! the body's true mass properties.
//!
//! The record is `brep_mass_properties(k, b, 1e-4, density 1, origin 0)`: an estimate at a
//! requested relative accuracy of `1e-4`, which ulp-level changes of the trims (this PR's
//! only geometric change) and of the integration centre (main's #17685, which follows the
//! tight box) move. For each row the test runs the case's Rust side with
//! `goldens::dump::capture` on, so the measured body is kept as an exact copy, and:
//! * checks that the run reproduces the row's committed value as the goldens check does
//!   (`values_agree`, `1e-9` relative; a bless keeps a line that agrees, so the committed
//!   value can be main's within that), so the copy is the body the golden measures;
//! * encloses that body's area, volume, centroid, axial inertias and products about the
//!   origin (`enclose_mass_properties`, Taylor-model sweep in rounded interval arithmetic;
//!   each asked `1e-5` of its scale wide; one that spends its cell budget stays a valid,
//!   wider band);
//! * asserts, per value, that the value the integrator converges to (`1e-8`) lies in its
//!   band, and that main's value, this branch's committed value and the run's value each
//!   lie within the requested
//!   accuracy of it: `1e-4` of the value's scale (the area, the volume, `R` for a centroid,
//!   `V R^2` for an inertia or product, `R` the bounding box's half diagonal, or the value
//!   where larger), as #16580's `round_definition_rows` does.
//!
//! The three fillet-then-shell rows record area, volume and mass only, and their bodies have
//! closed forms (`shell_closed_form`): those rows assert the converged value, main's and
//! this branch's each within the accuracy of the closed form instead. (The closed shell's
//! volume enclosure came out 5.9e8 wide, MEASURED; its cause is not investigated here.)
//!
//! A value whose band is at most its accuracy wide prints `PROVEN` (each recorded value is
//! then within twice its accuracy of the true one); a wider band prints `WIDE` and still
//! holds both values within their accuracy.
//!
//! Run (about 17 min on a 24-thread machine, so `#[ignore]`d; the goldens job checks the
//! values themselves):
//! `cargo test --profile goldens -p goldens --test wr729_moved_mass_rows_are_enclosed -- --ignored --nocapture`.

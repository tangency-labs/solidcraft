/// The rows `pick` takes, enclosed and checked as the module doc says.
fn check(pick: impl Fn(&str) -> bool) {
    let ctx = CaseContext {
        root: repo_root(),
        seeds: SEEDS,
    };
    let reg = registry();
    let unit = reg.iter().find(|u| u.id() == UNIT).unwrap();
    let cases = unit.cases(&ctx).unwrap();
    let rows: Vec<&Row> = ROWS.iter().filter(|r| pick(r.0)).collect();
    assert!(!rows.is_empty());
    let (mut proven, mut wide) = (0_usize, 0_usize);
    for &&(name, shell, main, ours) in &rows {
        let case = cases.iter().find(|c| c.name == name).unwrap();
        goldens::dump::capture();
        let out = unit.run_rust(case);
        let captured = goldens::dump::take();
        let out = out.unwrap();
        let (field, label) = if shell {
            ("shell_mass_properties", "shell_mass")
        } else {
            ("mass_properties", "mass")
        };
        // The goldens check (and so a bless) keeps a committed line whose values agree
        // with the run under `values_agree` (`1e-9` relative): the run may differ from the
        // committed row by that much, and both are held to the band below.
        let run: Vec<f64> = out.values.get(field).unwrap().clone();
        assert_eq!(run.len(), ours.len(), "{name}");
        for (i, (&x, &y)) in run.iter().zip(ours).enumerate() {
            assert!(
                values_agree(x, y, None),
                "{name}: the run's {field}[{i}] {x} does not reproduce this branch's row {y}"
            );
        }
        let mut bodies = captured.into_iter().filter(|c| c.label == label);
        let body = bodies.next().unwrap().brep.unwrap();
        assert!(
            bodies.next().is_none(),
            "{name}: more than one {label} body"
        );

        let k = Kernel::default();
        let store = AttributeStore::default();
        let attributes = PropertyAttributes {
            store: &store,
            key_of: &|_| ObjectKey(0),
        };
        let mut b = body.clone_standing_for_self().unwrap();
        let m = brep_mass_properties(
            &k,
            &mut b,
            ESTIMATE_ACCURACY_FINEST,
            1.0,
            Vec3::ZERO,
            &attributes,
        )
        .unwrap();
        let mut converged = vec![m.properties.area, m.properties.volume, m.properties.mass];
        if !shell {
            for v in [m.centroid, m.inertia, m.products] {
                converged.extend([v.x, v.y, v.z]);
            }
        }
        assert_eq!(converged.len(), ours.len(), "{name}");

        let mut b = body.clone_standing_for_self().unwrap();
        let r = 0.5
            * calculate_bounding_box(&k, &mut b, BoundingBoxOptions::default())
                .unwrap()
                .size()
                .length();
        // (what, band, scale) per entry of the record
        let mut entries: Vec<(&str, Bounds, f64)> = Vec::new();
        if shell {
            // area, volume, mass only: the shelled body's closed forms
            let (area, volume) = shell_closed_form(name);
            let at = |x: f64| Bounds {
                lo: x * (1.0 - CLOSED_FORM_ROUNDING),
                hi: x * (1.0 + CLOSED_FORM_ROUNDING),
            };
            entries.push(("area", at(area), area));
            entries.push(("volume", at(volume), volume));
            entries.push(("mass", at(volume), volume));
        } else {
            let e = enclose_mass_properties(&k, &mut b, ENCLOSURE_WIDTH).unwrap();
            if let Some((q, stop)) = e.short {
                eprintln!("{name}: the {q:?} enclosure stopped at {stop:?}, its band wider");
            }
            let v = e.volume.hi;
            let vr2 = v * r * r;
            entries.push(("area", e.area, e.area.hi));
            entries.push(("volume", e.volume, v));
            entries.push(("mass", e.volume, v));
            let names = [
                ["centroid x", "centroid y", "centroid z"],
                ["inertia x", "inertia y", "inertia z"],
                ["product yz", "product zx", "product xy"],
            ];
            for ((names, bands), scale) in names
                .into_iter()
                .zip([e.centroid, e.inertia, e.products])
                .zip([r, vr2, vr2])
            {
                for (w, x) in names.into_iter().zip(bands) {
                    entries.push((w, x, scale));
                }
            }
        }
        for (i, &(what, band, scale)) in entries.iter().enumerate() {
            let conv = converged[i];
            let accuracy = MASS_ACCURACY * scale.max(conv.abs());
            if shell {
                // a closed form: the converged estimate is within its accuracy of it too
                let off = (band.lo - conv).max(conv - band.hi).max(0.0);
                assert!(
                    off <= accuracy,
                    "{name}: the converged {what} {conv} is {off:e} off the closed form {band:?}"
                );
            } else {
                assert!(
                    band.contains(conv),
                    "{name}: the converged {what} {conv} is off the certified {band:?}"
                );
            }
            for (side, x) in [
                ("main's", main[i]),
                ("this branch's", ours[i]),
                ("the run's", run[i]),
            ] {
                let off = (band.lo - x).max(x - band.hi).max(0.0);
                assert!(
                    off <= accuracy,
                    "{name}: {side} {what} {x} is {off:e} off the certified {band:?}, past \
                     its accuracy {accuracy:e}"
                );
            }
            let label = if shell {
                proven += 1;
                "PROVEN (closed form)"
            } else if band.width() <= accuracy {
                proven += 1;
                "PROVEN"
            } else {
                wide += 1;
                "WIDE"
            };
            eprintln!(
                "MASSBAND {label} {name}: {what} main {}, ours {}, converged {conv}, band \
                 [{}, {}], width {:e} (accuracy {accuracy:e})",
                main[i],
                ours[i],
                band.lo,
                band.hi,
                band.width()
            );
        }
    }
    eprintln!(
        "MASSBAND SUMMARY {} rows: {proven} values PROVEN, {wide} WIDE",
        rows.len()
    );
}

/// The closed forms' own rounding (`PI` and a few operations), relative: far below the
/// record's accuracy.
const CLOSED_FORM_ROUNDING: f64 = 1e-12;

/// The area and volume of a fillet-then-shell row's body, in closed form. Each case
/// rounds edges of the box `[0, 30] x [0, 20] x [0, 10]` at r 3 and shells it 2 inward, so
/// every surface is a plane, a cylinder about a line or a sphere about a point, and the
/// body is a difference of parallel bodies of the core box `24 x 14 x 4` (r 3 rounds) or
/// of the core rectangle `24 x 14` (vertical rounds), whose measures are Steiner's
/// polynomials:
/// * all 12 edges: the outer surface is the core box `a x b x c = 24 x 14 x 4` grown by 3
///   and the inner one the same core grown by 1, with, for `s = a + b + c` and
///   `q = ab + bc + ca`, the area `A(r) = 2 q + 2 pi s r + 4 pi r^2` and the volume
///   `V(r) = abc + 2 q r + pi s r^2 + 4/3 pi r^3`; closed: area `A(3) + A(1)`, which is
///   `1952 + 376 pi`, and volume `V(3) - V(1)`, which is `1952 + 1112/3 pi`;
/// * the same, open at the top (its plane face at z = 10 removed): the slab
///   `[3, 27] x [3, 17] x [8, 10]` above the inner top goes, so the two `24 x 14` top
///   planes go and the rim, perimeter `76` by height `2`, comes: area `1952 + 376 pi -
///   672 + 152`, volume `1952 + 1112/3 pi - 672`;
/// * the 4 vertical edges: prisms of height 10 (outer, the core rectangle grown by 3) and
///   6 (inner, grown by 1, `[2, 8]` in z), with `A2(r) = 336 + 76 r + pi r^2` and
///   `P2(r) = 76 + 2 pi r`: area `2 A2(3) + 10 P2(3) + 2 A2(1) + 6 P2(1) = 3168 + 92 pi`,
///   volume `10 A2(3) - 6 A2(1) = 3168 + 84 pi`.
fn shell_closed_form(name: &str) -> (f64, f64) {
    use std::f64::consts::PI;
    match name {
        "real-box-fillet12-r3-shell-closed-issue-460" => {
            (1952.0 + 376.0 * PI, 1952.0 + 1112.0 / 3.0 * PI)
        }
        "real-box-fillet12-r3-shell-open-top-issue-460" => (
            1952.0 + 376.0 * PI - 672.0 + 152.0,
            1952.0 + 1112.0 / 3.0 * PI - 672.0,
        ),
        "real-box-fillet4v-r3-shell-closed" => (3168.0 + 92.0 * PI, 3168.0 + 84.0 * PI),
        _ => panic!("{name}: no closed form"),
    }
}

fn group(name: &str) -> usize {
    if name.starts_with("corner3x2-") || name.starts_with("overhang-") {
        0
    } else if name.starts_with("curve-sih-") || name.starts_with("source-") {
        1
    } else if name.starts_with("issue-880-") {
        2
    } else if name.starts_with("issue919-")
        || name.starts_with("issue920-")
        || name.starts_with("real-box-")
    {
        3
    } else {
        4
    }
}

